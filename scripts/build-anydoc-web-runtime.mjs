import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const packageDirectory = process.env.ANYDOC_PACKAGE_DIR
  ? resolve(process.env.ANYDOC_PACKAGE_DIR)
  : dirname(require.resolve('@firecrawl/anydoc-wasm/anydoc_wasm.js'))
const packageJson = JSON.parse(readFileSync(join(packageDirectory, 'package.json'), 'utf8'))
const expectedVersion = '0.1.7'

if (packageJson.version !== expectedVersion) {
  throw new Error(
    `Expected @firecrawl/anydoc-wasm ${expectedVersion}, found ${packageJson.version}. Review glue transforms.`
  )
}

let source = readFileSync(join(packageDirectory, 'anydoc_wasm.js'), 'utf8')
source = source.replace(/^export function /gm, 'function ')
source = source.replace(/export \{ initSync, __wbg_init as default \};\s*$/, '')
source = source.replace(
  "module_or_path = new URL('anydoc_wasm_bg.wasm', import.meta.url);",
  "throw new Error('Cherry Studio supplies the bundled anydoc WebAssembly bytes explicitly.');"
)
source += `\n;globalThis.__cherryAnydoc = Object.freeze({\n  init: module_or_path => __wbg_init({ module_or_path }),\n  toMarkdownBytes,\n  toDocument,\n  formatFromBytes,\n  formatFromExtension,\n  formatFromPath\n});\n`

if (/\bexport\s|\bimport\.meta\b/.test(source)) {
  throw new Error('The anydoc glue shape changed; refusing to emit an unsafe WebView runtime.')
}

const destination = join(repositoryRoot, 'src/agent/attachments/anydoc/generated/anydocWebRuntime.generated.ts')
mkdirSync(dirname(destination), { recursive: true })
writeFileSync(
  destination,
  `// Generated by scripts/build-anydoc-web-runtime.mjs from @firecrawl/anydoc-wasm ${expectedVersion}.\n` +
    `// Do not edit this file directly. anydoc is MIT licensed: https://github.com/firecrawl/anydoc\n` +
    `export const ANYDOC_WEB_RUNTIME_VERSION = ${JSON.stringify(expectedVersion)}\n` +
    `export const ANYDOC_WEB_RUNTIME_SOURCE = ${JSON.stringify(source)}\n`
)
